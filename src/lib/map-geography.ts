/**
 * Hand-traced, approximate geography drawn behind each journey's route: coastlines, lakes,
 * rivers, borders, hills and labels. Good enough to read as a map at phone size, not for
 * navigation. Coordinates are [lat, lng]; sea polygons run well past what any map shows.
 */

export type LatLng = readonly [number, number];

/** `minor` names (small lakes) only appear on the full-size map. */
export type MapLabel = { text: string; at: LatLng; kind: 'water' | 'region'; minor?: boolean };

export type Geography = {
  /** Seas and lakes, filled as water. */
  water: LatLng[][];
  /** Land drawn over water. */
  islands?: LatLng[][];
  rivers?: LatLng[][];
  borders?: LatLng[][];
  mountains?: LatLng[];
  forests?: LatLng[];
  labels?: MapLabel[];
};

/** A small oval lake or island. */
function oval(lat: number, lng: number, rLat: number, rLng: number, points = 14): LatLng[] {
  return Array.from({ length: points }, (_, i) => {
    const a = (i / points) * Math.PI * 2;
    return [lat + rLat * Math.sin(a), lng + rLng * Math.cos(a)] as const;
  });
}

